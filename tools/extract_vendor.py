#!/usr/bin/env python3
"""Extract the binaries a Glass build needs from the owner's raw system image.

Usage: extract_vendor.py SYSTEM_RAW LIST OUT_DIR

LIST has one path per line, relative to /system: `path`, or `src:dst` to store
the file under a different name. `#` starts a comment.
"""
import os
import shutil
import sys
import tempfile
from pathlib import Path

import inventory
from inventory import InventoryError


class ExtractError(Exception):
    pass


def _check_path(path: str, line: str) -> None:
    if not path or path.startswith("/") or ".." in path.split("/"):
        raise ExtractError(f"bad path in {line!r}: use a path relative to /system without '..'")


def parse_list(text: str) -> list:
    """(src, dst) pairs from a proprietary-files list; both are relative to /system."""
    entries, seen = [], set()
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        src, _, dst = line.partition(":")
        src, dst = src.strip(), (dst.strip() or src.strip())
        _check_path(src, line)
        _check_path(dst, line)
        if dst in seen:
            raise ExtractError(f"duplicate destination {dst}")
        seen.add(dst)
        entries.append((src, dst))
    return entries


def vendor_makefile(entries: list, vendor_dir: str = "vendor/glass/glass-1") -> str:
    lines = [f"    {vendor_dir}/proprietary/{dst}:system/{dst}" for _, dst in sorted(entries, key=lambda e: e[1])]
    return ("# Generated by glass-rom tools/extract_vendor.py from the owner's factory image. Do not commit.\n"
            "PRODUCT_COPY_FILES += \\\n" + " \\\n".join(lines) + "\n")


def _missing(image: str, dfs: str, entries: list) -> list:
    """Sources that debugfs cannot find; any other debugfs error is raised."""
    missing = []
    for src, _ in entries:
        if '"' in src:
            raise ExtractError(f"unsupported file name {src!r}")
        try:
            inventory.debugfs(dfs, image, f'stat "/{src}"')
        except InventoryError as e:
            if "File not found" not in str(e):
                raise
            missing.append(src)
    return missing


def extract(image: str, dfs: str, entries: list, out_dir: Path) -> None:
    """Write out_dir/proprietary/<dst> and out_dir/device-vendor.mk; all or nothing."""
    out_dir = Path(out_dir)
    if not os.path.isfile(image):
        raise ExtractError(f"{image}: no such file")
    missing = _missing(image, dfs, entries)
    if missing:
        raise ExtractError("not in the image: " + ", ".join(missing))
    out_dir.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=out_dir.parent, prefix=f".{out_dir.name}.") as tmp:
        new = Path(tmp) / "new"
        for src, dst in entries:
            target = new / "proprietary" / dst
            target.parent.mkdir(parents=True, exist_ok=True)
            inventory.debugfs(dfs, image, f'dump "/{src}" "{target}"')
            if not target.is_file():
                raise ExtractError(f"debugfs did not extract {src}")
        (new / "device-vendor.mk").write_text(vendor_makefile(entries))
        out_dir.mkdir(exist_ok=True)
        for name in ("proprietary", "device-vendor.mk"):
            dest = out_dir / name
            if dest.is_dir():
                shutil.rmtree(dest)
            os.replace(new / name, dest)


def main(argv):
    if len(argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    image, list_path, out_dir = argv
    try:
        dfs = inventory.find_tool("debugfs", ["/opt/homebrew/opt/e2fsprogs/sbin/debugfs",
                                              "/usr/local/opt/e2fsprogs/sbin/debugfs", "/sbin/debugfs"])
        with open(list_path) as f:
            entries = parse_list(f.read())
        extract(image, dfs, entries, Path(out_dir))
    except (ExtractError, InventoryError, OSError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    print(f"{len(entries)} files written to {out_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
