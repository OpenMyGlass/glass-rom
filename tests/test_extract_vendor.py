import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "tools"))
from extract_vendor import ExtractError, parse_list, vendor_makefile  # noqa: E402


class ParseListTest(unittest.TestCase):
    def test_plain_and_renamed(self):
        self.assertEqual(parse_list("lib/a.so\nvendor/x.bin:vendor/firmware/x.bin\n"),
                         [("lib/a.so", "lib/a.so"), ("vendor/x.bin", "vendor/firmware/x.bin")])

    def test_comments_and_blanks(self):
        self.assertEqual(parse_list("# c\n\nlib/a.so # tail\n"), [("lib/a.so", "lib/a.so")])

    def test_whitespace_and_crlf(self):
        self.assertEqual(parse_list("  lib/a.so  \r\n"), [("lib/a.so", "lib/a.so")])

    def test_rejects_bad_paths(self):
        for text in ("/lib/a.so\n", "lib/../a.so\n", "lib/a.so:/x\n", "a:b\nc:b\n", "lib/a.so\nlib/a.so\n"):
            with self.subTest(text=text), self.assertRaises(ExtractError):
                parse_list(text)


class MakefileTest(unittest.TestCase):
    def test_makefile(self):
        self.assertEqual(
            vendor_makefile([("lib/b.so", "lib/b.so"), ("etc/a.conf", "etc/a.conf")]),
            "# Generated by glass-rom tools/extract_vendor.py from the owner's factory image. Do not commit.\n"
            "PRODUCT_COPY_FILES += \\\n"
            "    vendor/glass/glass-1/proprietary/etc/a.conf:system/etc/a.conf \\\n"
            "    vendor/glass/glass-1/proprietary/lib/b.so:system/lib/b.so\n")


if __name__ == "__main__":
    unittest.main()
